#!/usr/bin/env python3

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time
from pathlib import Path
from typing import Any, Dict, Iterator, List, Optional, Tuple

PROJECT_ROOT = Path(__file__).resolve().parent
OPENAI_ENV_PATH = PROJECT_ROOT / "OPENAI.env"
DEFAULT_INPUT_PATH = PROJECT_ROOT / "databases.json"

DEFAULT_MODEL = "gpt-5.2"
DEFAULT_API_VERSION = "2025-04-01-preview"
DEFAULT_REASONING_EFFORT = "high"
DEFAULT_TEXT_VERBOSITY = "medium"


SYSTEM_PROMPT = """
You are an expert in gene set enrichment analysis databases, biological annotation
libraries, pathway resources, regulatory genomics, genome browsers, functional genomics,
disease-gene resources, drug perturbation signatures, ontology annotation systems, and
species-specific genome assemblies.

You will receive only two input fields:
- libraryName
- link

Your job is to generate exactly two output fields:
- species
- description_v2

Field requirements:

1. species
Return a concise semicolon-separated species set.
Examples:
- Human
- Mouse
- Human; Mouse
- Rat
- Zebrafish
- Fly
- Worm
- Yeast
- Human; Mouse; Rat
- Unknown

Use explicit species information from source documentation when available.

Infer species carefully from genome assemblies or source organism names:
- hg18, hg19, hg38, GRCh37, GRCh38 = Human
- mm9, mm10, mm39, GRCm = Mouse
- rn assemblies = Rat
- danRer = Zebrafish
- dm assemblies = Drosophila / Fly
- ce assemblies = C. elegans / Worm
- sacCer assemblies = S. cerevisiae / Yeast

If the library was generated by orthology mapping, mention that inside description_v2,
but keep species as a concise species set.

If species cannot be confidently determined, set:
Unknown

2. description_v2
Write one compact but informative description that merges all output fields except species.

The description_v2 must include, in natural language:
- Overall functional summary.
- The gene set enrichment question it helps answer.
- What the gene sets represent.
- Evidence type.
- Important interpretation/caveat.
- Suggested complementary libraries.
- Source notes, especially if the linked source is a legacy genome assembly,
  a database homepage, a publication, a download directory, or an inferred source.

Use this style:

"[Library_Name] is used for [main enrichment-analysis purpose]. In gene set enrichment
analysis, it helps answer: 'Do the genes in my input list appear to be enriched for
[type of biological feature/signature/annotation]?' The gene sets represent [what each
term corresponds to]. Evidence type: [curated knowledgebase / experimental evidence /
computational prediction / literature-mined association / differential-expression
signature / ontology annotation / regulatory motif prediction / protein interaction or
network-derived / clinical-disease association]. Important interpretation: [what an
enrichment hit means and does not prove]. Suggested complementary libraries: [2-5 related
resources]. Source notes: [source basis and limitations]."

Important caveat templates:
- For transcription-factor motif/PWM libraries:
  "An enrichment hit in [Library_Name] is not proof that a transcription factor binds
  or regulates those genes experimentally. It indicates that the submitted genes overlap
  more than expected with genes predicted to be associated with that transcription-factor
  motif. For stronger evidence, compare with ChIP-seq-based libraries such as ENCODE,
  ChEA, or ChEA3."

- For pathway libraries:
  "An enrichment hit suggests that the input genes are overrepresented in a known pathway,
  but it does not prove pathway activation, directionality, causality, or cell-type-specific
  activity."

- For drug-signature libraries:
  "An enrichment hit suggests similarity or inverse similarity to a perturbational
  expression signature, but it does not prove therapeutic efficacy or mechanism without
  experimental validation."

- For disease libraries:
  "An enrichment hit suggests overlap with genes associated with a disease or phenotype,
  but it does not prove that the input gene set causes the disease."

General requirements:
- Be concise but specific.
- Do not say only "used for enrichment analysis"; specify the biological signal being tested.
- Distinguish experimental evidence from computational prediction.
- Distinguish association from causation.
- Mention legacy genome assemblies or outdated source versions when relevant.
- If the library name is ambiguous, state the uncertainty in description_v2.
- Do not invent unsupported details.
- Prefer official documentation, database homepages, source files, and primary publications.
- Return valid JSON only, matching the requested schema.
"""


OUTPUT_SCHEMA: Dict[str, Any] = {
    "type": "object",
    "additionalProperties": False,
    "properties": {
        "species": {
            "type": "string",
            "description": (
                "Concise semicolon-separated species set, e.g. Human; Mouse, "
                "or Unknown if not confidently determined."
            ),
        },
        "description_v2": {
            "type": "string",
            "description": (
                "Compact functional summary containing all fields except species: "
                "overall purpose, GSEA question, gene set meaning, evidence type, "
                "interpretation caveat, complementary libraries, and source notes."
            ),
        },
    },
    "required": ["species", "description_v2"],
}


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def load_env_file(path: Path = OPENAI_ENV_PATH) -> None:
    """Load OPENAI.env without printing or exposing secrets."""

    if not path.exists():
        return

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue

        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key:
            os.environ[key] = value


def env_value(name: str, default: str) -> str:
    return os.getenv(name, default).strip() or default


def require_env(name: str) -> str:
    value = os.getenv(name, "").strip()
    if not value or value.startswith("replace-") or "your-rotated-resource" in value:
        raise EnvironmentError(f"{name} is not configured in {OPENAI_ENV_PATH}.")
    return value


def build_openai_client() -> Any:
    """Create an OpenAI client from OPENAI.env without making an API call."""
    from openai import AzureOpenAI

    load_env_file()
    provider = env_value("OPENAI_PROVIDER", "azure").lower()
    endpoint = require_env("AZURE_OPENAI_ENDPOINT")
    api_key = require_env("AZURE_OPENAI_API_KEY")
    api_version = env_value("AZURE_OPENAI_API_VERSION", DEFAULT_API_VERSION)
    return AzureOpenAI(
        azure_endpoint=endpoint,
        api_key=api_key,
        api_version=api_version,
    )


def atomic_write_json(path: Path, data: Any) -> None:
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    with tmp_path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    tmp_path.replace(path)


def iter_database_records(obj: Any) -> Iterator[Dict[str, Any]]:
    """
    Recursively find dict records containing libraryName.

    This supports:
      - a top-level list of records
      - a top-level dict containing nested lists
      - category-grouped JSON structures
    """
    if isinstance(obj, dict):
        if isinstance(obj.get("libraryName"), str):
            yield obj

        for value in obj.values():
            yield from iter_database_records(value)

    elif isinstance(obj, list):
        for item in obj:
            yield from iter_database_records(item)


def record_key(record: Dict[str, Any]) -> str:
    library_name = str(record.get("libraryName", "") or "").strip()
    link = str(record.get("link", "") or "").strip()
    return f"{library_name}\t{link}"


def load_cache(path: Optional[Path]) -> Dict[str, Dict[str, str]]:
    if path is None or not path.exists():
        return {}

    cache: Dict[str, Dict[str, str]] = {}
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue

            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                print(f"[WARN] Ignoring malformed cache line {line_no}", file=sys.stderr)
                continue

            key = str(obj.get("_key", "") or "")
            species = str(obj.get("species", "") or "").strip()
            description_v2 = str(obj.get("description_v2", "") or "").strip()

            if key and species and description_v2:
                cache[key] = {
                    "species": species,
                    "description_v2": description_v2,
                }

    return cache


def append_cache(path: Optional[Path], key: str, result: Dict[str, str]) -> None:
    if path is None:
        return

    payload = {
        "_key": key,
        "species": result["species"],
        "description_v2": result["description_v2"],
    }

    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(payload, ensure_ascii=False) + "\n")


def build_user_prompt(library_name: str, link: str) -> str:
    return f"""
Input enrichment-analysis library:

libraryName: {library_name}
link: {link}

Use only libraryName and link as the input fields. Ignore any previous description or
species values that may exist in the original JSON file.

Generate:
1. species
2. description_v2

	Return only valid JSON matching the schema.
	""".strip()


def is_web_search_disabled_error(exc: BaseException) -> bool:
    message = str(exc).lower()
    return (
        "web_search" in message
        and "disabled" in message
        and ("tool" in message or "tools" in message)
    )


def call_gpt_for_record(
    client: Any,
    library_name: str,
    link: str,
    model: str,
    reasoning_effort: str,
    text_verbosity: str,
    use_web: bool,
    require_web: bool,
    max_output_tokens: int,
    max_tool_calls: int,
    retries: int,
    sleep_base: float,
) -> Dict[str, str]:
    prompt = build_user_prompt(library_name, link)
    last_error: Optional[BaseException] = None
    web_enabled = use_web
    force_web = require_web

    attempt = 0
    while attempt <= retries:
        try:
            kwargs: Dict[str, Any] = {
                "model": model,
                "instructions": SYSTEM_PROMPT,
                "input": prompt,
                "reasoning": {"effort": reasoning_effort},
                "max_output_tokens": max_output_tokens,
                "store": False,
                "text": {
                    "verbosity": text_verbosity,
                    "format": {
                        "type": "json_schema",
                        "name": "enrichment_database_update",
                        "strict": True,
                        "schema": OUTPUT_SCHEMA,
                    }
                },
            }

            if web_enabled:
                kwargs["tools"] = [{"type": "web_search"}]
                kwargs["tool_choice"] = "required" if force_web else "auto"
                kwargs["max_tool_calls"] = max_tool_calls

            response = client.responses.create(**kwargs)

            parsed = json.loads(response.output_text)

            species = str(parsed.get("species", "") or "").strip()
            description_v2 = str(parsed.get("description_v2", "") or "").strip()

            if not species:
                raise ValueError("Model returned an empty species field.")
            if not description_v2:
                raise ValueError("Model returned an empty description_v2 field.")

            return {
                "species": species,
                "description_v2": description_v2,
            }

        except Exception as exc:
            last_error = exc

            if web_enabled and is_web_search_disabled_error(exc):
                print(
                    f"[WARN] {library_name}: hosted web_search is disabled for this "
                    f"organization. Falling back to {model} without web_search.",
                    file=sys.stderr,
                )
                web_enabled = False
                force_web = False
                continue

            if attempt >= retries:
                break

            wait_seconds = sleep_base * (2 ** attempt)
            print(
                f"[WARN] {library_name}: attempt {attempt + 1} failed: {exc}. "
                f"Retrying after {wait_seconds:.1f}s.",
                file=sys.stderr,
            )
            time.sleep(wait_seconds)
            attempt += 1

    raise RuntimeError(
        f"{library_name}: failed after {retries + 1} attempts. Last error: {last_error}"
    )


def update_record(record: Dict[str, Any], result: Dict[str, str]) -> None:
    record["description_v2"] = result["description_v2"]
    record["species"] = result["species"]


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Read databases.json, use libraryName/link as input to GPT, "
            "and add description_v2 plus updated species."
        )
    )

    parser.add_argument(
        "--input",
        default=str(DEFAULT_INPUT_PATH),
        help="Path to input databases.json. Default: local ./databases.json.",
    )
    parser.add_argument(
        "--output",
        default=None,
        help=(
            "Path to output JSON. Default: <input_stem>_v2.json. "
            "Use --in-place to overwrite input safely with a backup."
        ),
    )
    parser.add_argument(
        "--in-place",
        action="store_true",
        help="Overwrite the input file after creating a .bak backup.",
    )
    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
        help="OpenAI model ID or Azure deployment name. Default: gpt-5.2.",
    )
    parser.add_argument(
        "--reasoning-effort",
        default=DEFAULT_REASONING_EFFORT,
        choices=["none", "minimal", "low", "medium", "high", "xhigh"],
        help="Reasoning effort. Default: high.",
    )
    parser.add_argument(
        "--text-verbosity",
        default=DEFAULT_TEXT_VERBOSITY,
        choices=["low", "medium", "high"],
        help="GPT-5 text verbosity. Default: medium.",
    )
    parser.add_argument(
        "--no-web",
        action="store_true",
        help="Disable hosted web search. Not recommended for source-based library summaries.",
    )
    parser.add_argument(
        "--require-web",
        action="store_true",
        help="Require the model to call web_search for each record.",
    )
    parser.add_argument(
        "--max-output-tokens",
        type=int,
        default=1800,
        help="Maximum output tokens per library. Default: 1800.",
    )
    parser.add_argument(
        "--max-tool-calls",
        type=int,
        default=4,
        help="Maximum web_search tool calls per library. Default: 4.",
    )
    parser.add_argument(
        "--retries",
        type=int,
        default=3,
        help="Retries per failed record. Default: 3.",
    )
    parser.add_argument(
        "--sleep-base",
        type=float,
        default=2.0,
        help="Base exponential-backoff sleep after failures. Default: 2.0 seconds.",
    )
    parser.add_argument(
        "--sleep-between",
        type=float,
        default=0.0,
        help="Optional sleep between successful records to manage rate limits.",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Process only the first N eligible records. Useful for testing.",
    )
    parser.add_argument(
        "--start",
        type=int,
        default=0,
        help="Zero-based starting index among eligible records. Useful for chunking.",
    )
    parser.add_argument(
        "--skip-existing",
        action="store_true",
        help="Skip records that already have a non-empty description_v2 field.",
    )
    parser.add_argument(
        "--cache-jsonl",
        default="enrichment_database_update_cache.jsonl",
        help=(
            "JSONL cache file. Prevents repeated API calls for the same libraryName/link. "
            "Use an empty string to disable."
        ),
    )
    parser.add_argument(
        "--checkpoint-every",
        type=int,
        default=1,
        help="Write output after every N updated records. Default: 1.",
    )

    args = parser.parse_args()

    input_path = Path(args.input)
    if not input_path.is_absolute():
        input_path = PROJECT_ROOT / input_path

    if args.in_place:
        output_path = input_path
    elif args.output:
        output_path = Path(args.output)
    else:
        output_path = input_path.with_name(f"{input_path.stem}_v2{input_path.suffix}")

    cache_path = None if args.cache_jsonl == "" else Path(args.cache_jsonl)

    data = load_json(input_path)
    records = list(iter_database_records(data))

    if not records:
        raise ValueError("No records containing 'libraryName' were found.")

    eligible: List[Tuple[int, Dict[str, Any]]] = []
    for i, record in enumerate(records):
        library_name = str(record.get("libraryName", "") or "").strip()
        if not library_name:
            continue

        if args.skip_existing and str(record.get("description_v2", "") or "").strip():
            continue

        eligible.append((i, record))

    if args.start:
        eligible = eligible[args.start:]

    if args.limit is not None:
        eligible = eligible[: args.limit]

    if args.in_place:
        backup_path = input_path.with_suffix(input_path.suffix + ".bak")
        shutil.copy2(input_path, backup_path)
        print(f"[INFO] Backup written to {backup_path}")

    print(f"[INFO] Total records found: {len(records)}")
    print(f"[INFO] Eligible records to process: {len(eligible)}")
    print(f"[INFO] Output path: {output_path}")
    print(f"[INFO] Model: {args.model}")
    print(f"[INFO] Reasoning effort: {args.reasoning_effort}")
    print(f"[INFO] Text verbosity: {args.text_verbosity}")
    print(f"[INFO] Web search enabled: {not args.no_web}")
    print(f"[INFO] Require web search: {args.require_web and not args.no_web}")

    client = build_openai_client()
    cache = load_cache(cache_path)

    updated = 0
    failed = 0

    for local_idx, (global_idx, record) in enumerate(eligible, start=1):
        library_name = str(record.get("libraryName", "") or "").strip()
        link = str(record.get("link", "") or "").strip()
        key = record_key(record)

        print(f"[RUN] {local_idx}/{len(eligible)} record_index={global_idx} {library_name}")

        try:
            if key in cache:
                result = cache[key]
                print(f"[CACHE] {library_name}")
            else:
                result = call_gpt_for_record(
                    client=client,
                    library_name=library_name,
                    link=link,
                    model=args.model,
                    reasoning_effort=args.reasoning_effort,
                    text_verbosity=args.text_verbosity,
                    use_web=not args.no_web,
                    require_web=args.require_web,
                    max_output_tokens=args.max_output_tokens,
                    max_tool_calls=args.max_tool_calls,
                    retries=args.retries,
                    sleep_base=args.sleep_base,
                )
                append_cache(cache_path, key, result)
                cache[key] = result

            update_record(record, result)
            updated += 1

            print(f"[OK] {library_name} -> species={result['species']}")

            if updated % args.checkpoint_every == 0:
                atomic_write_json(output_path, data)
                print(f"[CHECKPOINT] Wrote {output_path}")

            if args.sleep_between > 0:
                time.sleep(args.sleep_between)

        except Exception as exc:
            failed += 1
            print(f"[ERROR] {library_name}: {exc}", file=sys.stderr)

            record["description_v2_error"] = str(exc)

            atomic_write_json(output_path, data)
            print(f"[CHECKPOINT] Wrote {output_path} after error")

    atomic_write_json(output_path, data)

    print("[DONE]")
    print(f"[DONE] Updated records: {updated}")
    print(f"[DONE] Failed records: {failed}")
    print(f"[DONE] Output written to: {output_path}")


if __name__ == "__main__":
    main()
